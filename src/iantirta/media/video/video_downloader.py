@dataclass(slots=True)
class VideoMetadata:
    """YT Downloaded result metadata."""
    id: str
    title: str
    duration: int

    thumbnail: str
    tags: str

    # If Autogenerated By Youtibe
    album: str | None = None
    artists: list | None = None
    track: str | None = None
    release_date = None
    release_year = None

    artist: str | None = None
    channel: str | None = None
    creators: str | None = None

    video_path: Path | None = None

    _resolved_artist: str | None = None

    @classmethod
    def from_dict(cls, **datas) -> "VideoMetadata":
        valid_keys = {f.name for f in fields(cls)}
        valid_datas = {k: v for k, v in datas.items() if k in valid_keys}

        return cls(**valid_datas)

    @property
    def resolved_artist(self) -> str:
        if self._resolved_artist is None:
            if self.artist is not None:
                self._resolved_artist = self.artist

            elif self.artists:
                if len(self.artists) == 1:
                    self._resolved_artist = self.artists[0]
                elif len(self.artists) > 1:
                    _logger.warning(f"Artists is multiple but still not implemented for it: {self.artists}")

            if self._resolved_artist is None:
                candidate_keys = ["creators", "channel"]
                candidates = set()
                for can in candidate_keys:
                    if (artist_can := getattr(self, can, None)) is not None:
                        candidates.add(artist_can.lower())

                if candidates:
                    if len(candidates) > 1:
                        _logger.warning(f"Artists candidates is multiple but still not implemented for it: {candidates}")
                    
                    self._resolved_artist = next(iter(candidates)).title()

            if self._resolved_artist is None:
                raise ValueError("Could not resolve artist")
    
        return self._resolved_artist


@dataclass
class VideoDownloader:
    """YTDLP Wrapper"""

    format: Literal["best-audio"] = "best-audio"
    output_dir: str | Path = constants.DEFAULT_VIDEO_DOWNLOAD_DIR
    retries: int = 3
    socket_timeout: int = 30
    logger: logging.Logger | None = None

    cookiefile: str | Path = constants.DEFAULT_COOKIEPATH

    def __post_init__(self):
        if not self.logger:
            self.logger = _logger
            self.logger.setLevel(logging.DEBUG)

        if (
            self.cookiefile == constants.DEFAULT_COOKIEPATH
            and constants.DEFAULT_NOROTATE_COOKIEPATH.is_file()
        ):
            self.cookiefile = constants.DEFAULT_NOROTATE_COOKIEPATH
            install_deno()

        self.cookiefile = str(self.cookiefile)

        self.logger.debug(
            f"Using Cookie configuration file at: {self.cookiefile}"
        )

    @property
    def yt_options(self) -> dict[str, str]:
        return {
            "cookiefile": self.cookiefile,
            "format": (
                "bestvideo[height<=720][ext=mp4]+"
                "bestaudio[ext=m4a]/best[ext=mp4]/best"
            ),
            "merge_output_format": "mp4",
            "outtmpl": str(Path(self.output_dir) / "%(title)s.%(ext)s"),
            "noplaylist": True,

            "quiet": True,
            "no_warnings": True,
            "noprogress": True,
            "continuedl": False,

            "remote_components": ["ejs:npm"],
            "retries": self.retries,
            "fragment_retries": self.retries,
            "socket_timeout": self.socket_timeout,
            "cachedir": str(
                constants.DEFAULT_VIDEO_DOWNLOAD_DIR /
                "yt-dlp-cache"
            ),
        }

    def download(
        self,
        url: str,
        *,
        output_dir: str | Path | None = None,
        max_attempts: int = 5,
        logger=None
    ) -> VideoMetadata:
        import yt_dlp.networking.exceptions
        from yt_dlp import YoutubeDL

        if output_dir is not None:
            self.output_dir = Path(output_dir).expanduser().resolve()

        attempt = 0
        while True:
            attempt += 1
            try:
                (logger or self.logger).debug(
                    f'downloading video ({attempt}/{max_attempts}): url="{url}", output="{self.output_dir!s}"'
                )
                with YoutubeDL(self.yt_options) as ydl:
                    info = ydl.extract_info(url, download=True)
                    video_path = Path(ydl.prepare_filename(info))
                    return VideoMetadata.from_dict(**info, video_path=video_path)
            except Exception as e:
                if attempt >= max_attempts:
                    (logger or self.logger).warning(f"Download error: {e}")
                    raise
                if (
                    isinstance(e, yt_dlp.networking.exceptions.HTTPError)
                    or ErrorType(e) in (ErrorType.RATE_LIMIT,)
                ):
                    time.sleep(1)
                else:
                    (logger or self.logger).warning(f"Download error: {e}")
                    raise

    def extract_info(self, url: str, *, logger=None) -> VideoMetadata:
        from yt_dlp import YoutubeDL

        with YoutubeDL(self.yt_options) as ydl:
            return VideoMetadata.from_dict(**ydl.extract_info(url, download=False))

    def batch_download(self, urls: list[str]) -> list[VideoMetadata]:
        from yt_dlp import YoutubeDL

        with YoutubeDL(self.yt_options) as ydl:
            ydl.download(urls)


def download_one_video(url, *, logger=None, **kwargs) -> VideoMetadata:
    return VideoDownloader().download(url)


def extract_video_info(url, *, logger=None, **kwargs) -> VideoMetadata:
    return VideoDownloader().extract_info(url)


def install_deno():
    is_termux = (
        platform.system().lower() == 'android'
        and Path('/data/data/com.termux').exists()
    )
    if is_termux:
        deno_home = Path('/data/data/com.termux/files/usr/bin/')
    else:
        deno_home = Path.home() / ".deno" / "bin"
    deno_bin = deno_home / ("deno.exe" if os.name == "nt" else "deno")

    if not deno_bin.exists():
        _logger.debug('Downloading deno...')

        if os.name == "nt":
            cmd = [
                "powershell", "-NoProfile",
                "-Command", "irm https://deno.land/install.ps1 | iex"
            ]
            is_shell = False

        elif is_termux:
            cmd = 'pkg install deno -y'
            is_shell = True

        else:
            cmd = "curl -fsSL https://deno.land/install.sh | sh"
            is_shell = True

        try:
            subprocess.run(
                cmd,
                shell=is_shell,
                check=True,
                capture_output=True,
                text=True
            )
        except subprocess.CalledProcessError as e:
            raise RuntimeError(
                "Deno installation failed!\n"
                f"STDOUT: {e.stdout}\nSTDERR: {e.stderr}"
            ) from e

    if str(deno_home) not in os.environ.get("PATH", ""):
        _logger.debug('adding deno to environment path...')
        os.environ["PATH"] = f"{deno_home}{os.pathsep}{os.environ['PATH']}"


